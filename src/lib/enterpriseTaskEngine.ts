// Event listeners for task updates
type TaskChangeListener = (tasks: EnterpriseTask[]) => void;
const listeners: TaskChangeListener[] = [];

export const subscribeToEnterpriseTasks = (listener: TaskChangeListener) => {
  listeners.push(listener);
  listener([...mockEnterpriseTasks]);
  return () => {
    const idx = listeners.indexOf(listener);
    if (idx > -1) listeners.splice(idx, 1);
  };
};

const notifyListeners = () => {
  listeners.forEach(fn => fn([...mockEnterpriseTasks]));
};

export const getEnterpriseTasks = () => [...mockEnterpriseTasks];

