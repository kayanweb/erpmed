// Auto-trigger engine based on hospital events
export const triggerAutoTaskEngine = (
  event: AutoTaskTriggerEvent,
  contextData: {
    patientId?: string;
    patientMRN?: string;
    patientNameAr?: string;
    patientNameEn?: string;
    department?: HospitalDepartmentId;
    orderId?: string;
    detailsAr?: string;
    detailsEn?: string;
    value?: string;
  }
) => {
  let titleAr = "";
  let titleEn = "";
  let category: TaskCategory = "clinical";
  let targetDept: HospitalDepartmentId = "nursing";
  let priority: TaskPriority = "normal";
  let slaMinutes = 60;

  switch (event) {
    case "code_blue_triggered":
      titleAr = `تفعيل كود أزرق Code Blue - ${contextData.detailsAr || "قسم العناية"}`;
      titleEn = `Code Blue Activated - ${contextData.detailsEn || "ICU / Ward"}`;
      priority = "code_blue";
      slaMinutes = 3;
      category = "clinical";
      targetDept = "er";
      break;
    case "critical_result_flagged":
      titleAr = `إشعار نتيجة تحليل حرجة - ${contextData.value || "الدم"}`;
      titleEn = `Critical Laboratory Result Flagged - ${contextData.value || "Blood"}`;
      priority = "critical";
      slaMinutes = 15;
      category = "laboratory";
      targetDept = "icu";
      break;
    case "stroke_alert":
      titleAr = "إنذار جلطة دماغية حادة Stroke Alert - تصوير مقطعي عاجل";
      titleEn = "Stroke Alert - Immediate Non-contrast CT Scan";
      priority = "stat";
      slaMinutes = 20;
      category = "radiology";
      targetDept = "ris";
      break;
    case "low_stock_warning":
      titleAr = `تنبيه انخفاض مخزون دواء/مستلزم: ${contextData.value || "مستلزمات حادة"}`;
      titleEn = `Low Inventory Stock Level: ${contextData.value || "Medical Supplies"}`;
      priority = "high";
      slaMinutes = 120;
      category = "pharmacy";
      targetDept = "pharmacy";
      break;
    default:
      titleAr = `مهمة تلقائية: ${event}`;
      titleEn = `Auto Task: ${event}`;
      break;
  }

  return createEnterpriseTask({
    titleAr,
    titleEn,
    descriptionAr: contextData.detailsAr || titleAr,
    descriptionEn: contextData.detailsEn || titleEn,
    category,
    originDepartment: contextData.department || "administration",
    targetDepartment: targetDept,
    priority,
    slaMinutes,
    patientId: contextData.patientId,
    patientMRN: contextData.patientMRN,
    patientNameAr: contextData.patientNameAr,
    patientNameEn: contextData.patientNameEn,
    orderId: contextData.orderId,
    isAutoGenerated: true,
    triggerEvent: event
  });
};

// 13-Step Workflow state updates
export const updateTaskWorkflowState = (
  taskId: string,
  newStatus: TaskStatus,
  actionData: {
    performedBy: string;
    performedByName: string;
    noteContent?: string;
    progressPercentage?: number;
    assignedToUser?: { id: string; name: string };
    attachment?: { fileName: string; fileType: string; fileUrl: string };
  }
) => {
  mockEnterpriseTasks = mockEnterpriseTasks.map(task => {
    if (task.id !== taskId) return task;

    const oldStatus = task.status;
    const now = new Date().toISOString();
    const updatedNotes = [...task.notes];
    const updatedAttachments = [...task.attachments];

    if (actionData.noteContent) {
      updatedNotes.push({
        id: `note-${Date.now()}`,
        authorId: actionData.performedBy,
        authorName: actionData.performedByName,
        role: "Staff",
        content: actionData.noteContent,
        timestamp: now
      });
    }

    if (actionData.attachment) {
      updatedAttachments.push({
        id: `att-${Date.now()}`,
        fileName: actionData.attachment.fileName,
        fileType: actionData.attachment.fileType,
        fileUrl: actionData.attachment.fileUrl,
        uploadedBy: actionData.performedByName,
        uploadedAt: now
      });
    }

    const auditLog = {
      id: `aud-${Date.now()}`,
      taskId,
      action: `STATUS_CHANGE_${newStatus.toUpperCase()}`,
      performedBy: actionData.performedBy,
      performedByName: actionData.performedByName,
      previousStatus: oldStatus,
      newStatus,
      timestamp: now,
      details: `Status transitioned from ${oldStatus} to ${newStatus}`
    };

    return {
      ...task,
      status: newStatus,
      progressPercentage: actionData.progressPercentage !== undefined ? actionData.progressPercentage : (newStatus === "completed" || newStatus === "closed" ? 100 : task.progressPercentage),
      assignedToUserId: actionData.assignedToUser ? actionData.assignedToUser.id : task.assignedToUserId,
      assignedToUserName: actionData.assignedToUser ? actionData.assignedToUser.name : task.assignedToUserName,
      acceptedAt: newStatus === "accepted" ? now : task.acceptedAt,
      startedAt: newStatus === "in_progress" ? now : task.startedAt,
      completedAt: newStatus === "completed" ? now : task.completedAt,
      verifiedAt: newStatus === "verified" ? now : task.verifiedAt,
      closedAt: newStatus === "closed" ? now : task.closedAt,
      notes: updatedNotes,
      attachments: updatedAttachments,
      auditLogs: [auditLog, ...task.auditLogs]
    };
  });

  notifyListeners();
};
